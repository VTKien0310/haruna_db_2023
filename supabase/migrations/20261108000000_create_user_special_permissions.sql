create table public.user_special_permissions (
    id integer generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    created_at timestamp with time zone not null default now(),
    permission integer not null check (permission >= 0),
    unique (user_id, permission)
);

alter table public.user_special_permissions enable row level security;

revoke all on table public.user_special_permissions from anon, authenticated;
grant select on table public.user_special_permissions to authenticated;
grant all on table public.user_special_permissions to service_role;

create policy "Users can read their own special permissions"
on public.user_special_permissions
for select
to authenticated
using ((select auth.uid()) = user_id);
