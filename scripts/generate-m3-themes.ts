import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {
  Blend,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
  type DynamicColor,
} from "@material/material-color-utilities";
import { THEME_OPTIONS } from "../src/modules/master/ThemeEntities.ts";

const outputPath = fileURLToPath(
  new URL("../src/libs/ui/styles/m3-schemes.css", import.meta.url),
);
const customColors = {
  success: "#2e7d32",
  warning: "#f59e0b",
} as const;
const roleEntries = Object.entries(MaterialDynamicColors).filter(
  ([name, color]) =>
    !name.endsWith("PaletteKeyColor") &&
    typeof color === "object" &&
    color !== null &&
    "getArgb" in color,
);

function kebabCase(value: string): string {
  return value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function getCustomColors(
  seed: number,
  isDark: boolean,
): Record<string, string> {
  return Object.fromEntries(
    Object.entries(customColors).flatMap(([name, source]) => {
      const palette = TonalPalette.fromInt(
        Blend.harmonize(argbFromHex(source), seed),
      );
      const tones = isDark
        ? { color: 80, onColor: 20, container: 30, onContainer: 90 }
        : { color: 40, onColor: 100, container: 90, onContainer: 10 };

      return [
        [`${name}`, hexFromArgb(palette.tone(tones.color))],
        [`on-${name}`, hexFromArgb(palette.tone(tones.onColor))],
        [`${name}-container`, hexFromArgb(palette.tone(tones.container))],
        [`on-${name}-container`, hexFromArgb(palette.tone(tones.onContainer))],
      ];
    }),
  );
}

function getThemeColors(
  theme: (typeof THEME_OPTIONS)[number],
): Record<string, string> {
  const seed = argbFromHex(theme.seed);
  const scheme = new SchemeTonalSpot(
    Hct.fromInt(seed),
    theme.colorScheme === "dark",
    0,
  );
  const colors = Object.fromEntries(
    roleEntries.map(([name, color]) => [
      kebabCase(name),
      hexFromArgb((color as DynamicColor).getArgb(scheme)),
    ]),
  );

  return { ...colors, ...getCustomColors(seed, theme.colorScheme === "dark") };
}

function declarations(colors: Record<string, string>): string {
  return Object.entries(colors)
    .map(([name, value]) => `  --color-${name}: ${value};`)
    .join("\n");
}

const generatedThemes = THEME_OPTIONS.map((theme) => ({
  theme,
  colors: getThemeColors(theme),
}));
const mismatches = generatedThemes.filter(
  ({ theme, colors }) =>
    theme.themeColor.toLowerCase() !== colors.surface.toLowerCase(),
);

if (mismatches.length > 0) {
  console.error("Theme color must match its generated M3 surface role:");
  for (const { theme, colors } of mismatches) {
    console.error(`  ${theme.id}: ${theme.themeColor} -> ${colors.surface}`);
  }
  throw new Error(
    "Update themeColor in ThemeEntities.ts before generating CSS.",
  );
}

const [fallback, ...overrides] = generatedThemes;
const css = `/* Generated by scripts/generate-m3-themes.ts. Do not edit by hand. */
@theme static {
  --color-*: initial;
${declarations(fallback.colors)}
}

${overrides
  .map(
    ({ theme, colors }) =>
      `:root[data-theme="${theme.id}"] {\n  color-scheme: ${theme.colorScheme};\n${declarations(colors)}\n}`,
  )
  .join("\n\n")}
`;

await writeFile(outputPath, css);
